/** Tri par numéro d'inventaire (« p04-07 » → 7) : l'ordre des captures. */
export function byNumber(defs: LayoutDef[]): LayoutDef[] {
  return [...defs].sort((a, b) => Number(a.id.split('-')[1]) - Number(b.id.split('-')[1]))
}

